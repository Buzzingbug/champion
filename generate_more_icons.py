# 5. Rocket / Boost Icon (Magenta/Purple)
ic_boost = c_icon()
d = ImageDraw.Draw(ic_boost)
d.polygon([(32, 10), (46, 24), (42, 42), (32, 38), (22, 42), (18, 24)], fill=(210, 80, 255, 240))
d.polygon([(18, 32), (8, 44), (20, 42)], fill=(170, 40, 255, 240))
